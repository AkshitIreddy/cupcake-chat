#!/usr/bin/env node
import { cp, mkdir, rm, writeFile } from 'node:fs/promises';
import { isAbsolute, join, relative, resolve } from 'node:path';
import { exists, parseArgValue, repoRoot, sha256File, walkFiles } from './lib/process.mjs';

const args = process.argv.slice(2);
const source = join(repoRoot, 'packaging', 'fixtures');
const destination = resolve(
  parseArgValue(args, '--destination', join(repoRoot, 'out', 'test-fixtures')),
);
const clean = args.includes('--clean');
const marker = join(destination, '.cupcake-fixture');
const relativeDestination = relative(join(repoRoot, 'out'), destination);

if (
  !relativeDestination ||
  relativeDestination.startsWith('..') ||
  isAbsolute(relativeDestination)
) {
  throw new Error('Fixture destination must be a child of the repository out/ directory.');
}

if (clean && (await exists(destination)) && !(await exists(marker))) {
  throw new Error(`Refusing to clean an unmarked fixture directory: ${destination}`);
}
if (clean) await rm(destination, { recursive: true, force: true });

await mkdir(destination, { recursive: true });
await writeFile(marker, 'Disposable fixtures generated by scripts/setup-fixtures.mjs\n', 'utf8');
await cp(source, destination, { recursive: true, force: true });

const files = (await walkFiles(destination)).filter(
  (file) => file !== marker && !file.endsWith('fixture-manifest.json'),
);
const manifest = {
  schemaVersion: 1,
  fixtureId: '00000000-0000-7000-8000-000000000001',
  projectId: '00000000-0000-7000-8000-000000000002',
  generatedAt: '2026-01-01T00:00:00.000Z',
  files: await Promise.all(
    files.sort().map(async (file) => ({
      path: relative(destination, file).split('\\').join('/'),
      sha256: await sha256File(file),
    })),
  ),
};
await writeFile(
  join(destination, 'fixture-manifest.json'),
  `${JSON.stringify(manifest, null, 2)}\n`,
  'utf8',
);
process.stdout.write(
  `Prepared ${manifest.files.length} deterministic fixtures in ${relative(repoRoot, destination)}.\n`,
);
