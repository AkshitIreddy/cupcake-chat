import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repositoryRoot = resolve(packageRoot, '..', '..');
const schemaRoot = resolve(packageRoot, 'schema', 'v1');
const manifestPath = resolve(schemaRoot, 'manifest.json');
const pythonOutput = resolve(
  repositoryRoot,
  'services',
  'runtime',
  'src',
  'cupcake_runtime',
  'generated',
  'contracts_v1.py',
);
const rustOutput = resolve(
  repositoryRoot,
  'crates',
  'tool-broker',
  'src',
  'generated',
  'contracts_v1.rs',
);
const checkOnly = process.argv.includes('--check');

async function main() {
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  if (manifest.contractVersion !== 1) {
    throw new Error(`Unsupported contract manifest version: ${manifest.contractVersion}`);
  }

  const documents = await Promise.all(
    manifest.schemas.map(async ({ name, file }) => ({
      name,
      file,
      schema: JSON.parse(await readFile(resolve(schemaRoot, file), 'utf8')),
    })),
  );

  await emit(pythonOutput, renderPython(documents));
  await emit(rustOutput, renderRust(documents));
}

async function emit(path, contents) {
  if (checkOnly) {
    const existing = await readExisting(path);
    if (existing !== contents) {
      throw new Error(`Generated language binding is stale: ${path}`);
    }
    return;
  }
  await writeFile(path, contents);
}

async function readExisting(path) {
  try {
    return await readFile(path, 'utf8');
  } catch (error) {
    if (error && typeof error === 'object' && error.code === 'ENOENT') return undefined;
    throw error;
  }
}

function renderPython(entries) {
  const lines = [
    '# Generated by packages/contracts/scripts/generate-language-bindings.mjs.',
    '# Source: packages/contracts/schema/v1. DO NOT EDIT.',
    '# ruff: noqa',
    'from __future__ import annotations',
    '',
    'from typing import Annotated, Any, Literal, cast',
    '',
    'from pydantic import BaseModel, ConfigDict, Field, RootModel',
    '',
    'CONTRACT_VERSION: Literal[1] = 1',
    'type JsonValue = None | bool | int | float | str | list[JsonValue] | dict[str, JsonValue]',
    '',
    '',
    'class StrictGeneratedModel(BaseModel):',
    '    """Closed Pydantic boundary generated from a product JSON Schema."""',
    '',
    '    model_config = ConfigDict(extra="forbid", strict=True, frozen=True, populate_by_name=False)',
    '',
  ];

  const exports = ['CONTRACT_VERSION', 'JsonValue', 'StrictGeneratedModel'];
  for (const entry of entries) {
    const rootName = rootTypeName(entry.schema, entry.name);
    const context = { definitions: [], used: new Map() };
    pythonType(entry.schema, rootName, context, true);
    lines.push('', ...context.definitions);
    exports.push(rootName);
  }
  lines.push('', '', '__all__ = [');
  for (const name of exports) lines.push(`    ${JSON.stringify(name)},`);
  lines.push(']', '');
  return `${lines.join('\n')}\n`;
}

function pythonType(schema, suggestedName, context, declare = false) {
  if (schema.$ref === 'T0') return 'JsonValue';
  if (schema.$id === 'T0') return 'JsonValue';

  if (Array.isArray(schema.anyOf)) {
    const literals = schema.anyOf.filter((item) => Object.hasOwn(item, 'const'));
    if (literals.length === schema.anyOf.length) {
      return `Literal[${literals.map((item) => pyLiteral(item.const)).join(', ')}]`;
    }
    const variants = unique(
      schema.anyOf.map((item, index) =>
        pythonType(item, `${suggestedName}Variant${index + 1}`, context),
      ),
    );
    const union = variants.join(' | ');
    if (declare) {
      context.definitions.push(
        `class ${suggestedName}(RootModel[${union}]):`,
        `    """Generated root union for the ${suggestedName} contract."""`,
        '',
        `    root: ${union}`,
        '',
      );
      return suggestedName;
    }
    return union;
  }

  if (Object.hasOwn(schema, 'const')) return `Literal[${pyLiteral(schema.const)}]`;

  if (schema.type === 'object') {
    if (schema.patternProperties || schema.additionalProperties === true) {
      const valueSchema = schema.patternProperties
        ? Object.values(schema.patternProperties)[0]
        : undefined;
      return `dict[str, ${valueSchema ? pythonType(valueSchema, `${suggestedName}Value`, context) : 'JsonValue'}]`;
    }

    const className = uniqueName(suggestedName, context.used);
    const required = new Set(schema.required ?? []);
    const fields = [];
    for (const [property, propertySchema] of Object.entries(schema.properties ?? {})) {
      const fieldName = pythonFieldName(property);
      const childName = `${className}${pascal(property)}`;
      const type = pythonConstrainedType(propertySchema, childName, context);
      const arguments_ = [];
      if (fieldName !== property) arguments_.push(`alias=${JSON.stringify(property)}`);
      for (const [keyword, pydanticName] of [
        ['minimum', 'ge'],
        ['maximum', 'le'],
        ['minLength', 'min_length'],
        ['maxLength', 'max_length'],
        ['minItems', 'min_length'],
        ['maxItems', 'max_length'],
        ['pattern', 'pattern'],
      ]) {
        if (Object.hasOwn(propertySchema, keyword)) {
          arguments_.push(`${pydanticName}=${pyLiteral(propertySchema[keyword])}`);
        }
      }
      if (!required.has(property) && Object.hasOwn(propertySchema, 'default')) {
        arguments_.push(`default=${pyLiteral(propertySchema.default)}`);
      } else if (!required.has(property)) {
        arguments_.push('default=cast(Any, None)');
      }
      const field = arguments_.length > 0 ? ` = Field(${arguments_.join(', ')})` : '';
      fields.push(`    ${fieldName}: ${type}${field}`);
    }
    context.definitions.push(
      `class ${className}(StrictGeneratedModel):`,
      ...(fields.length > 0 ? fields : ['    pass']),
      '',
    );
    return className;
  }

  if (schema.type === 'array') {
    return `list[${pythonType(schema.items ?? {}, `${suggestedName}Item`, context)}]`;
  }
  if (schema.type === 'string') return 'str';
  if (schema.type === 'integer') return 'int';
  if (schema.type === 'number') return 'float';
  if (schema.type === 'boolean') return 'bool';
  if (schema.type === 'null') return 'None';
  return 'JsonValue';
}

function pythonConstrainedType(schema, suggestedName, context) {
  const base = pythonType(schema, suggestedName, context);
  if (schema.type === 'array' && schema.uniqueItems) {
    return `Annotated[${base}, Field(json_schema_extra={"uniqueItems": True})]`;
  }
  return base;
}

function renderRust(entries) {
  const lines = [
    '// Generated by packages/contracts/scripts/generate-language-bindings.mjs.',
    '// Source: packages/contracts/schema/v1. DO NOT EDIT.',
    '#![allow(clippy::large_enum_variant)]',
    '#![allow(clippy::derive_partial_eq_without_eq)]',
    '',
    'use serde::{Deserialize, Serialize};',
    '',
    'pub const CONTRACT_VERSION: u16 = 1;',
    'pub type JsonValue = serde_json::Value;',
    '',
    '#[derive(Debug, Clone, Copy, PartialEq, Eq)]',
    'pub struct ContractVersion1;',
    '',
    'impl Serialize for ContractVersion1 {',
    '    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>',
    '    where',
    '        S: serde::Serializer,',
    '    {',
    '        serializer.serialize_u16(CONTRACT_VERSION)',
    '    }',
    '}',
    '',
    "impl<'de> Deserialize<'de> for ContractVersion1 {",
    '    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>',
    '    where',
    "        D: serde::Deserializer<'de>,",
    '    {',
    '        let value = u16::deserialize(deserializer)?;',
    '        if value == CONTRACT_VERSION {',
    '            Ok(Self)',
    '        } else {',
    '            Err(serde::de::Error::custom(format!("unsupported contract version {value}")))',
    '        }',
    '    }',
    '}',
    '',
  ];

  for (const entry of entries) {
    const moduleName = rustFieldName(entry.name.replaceAll('-', '_'));
    const rootName = rootTypeName(entry.schema, entry.name);
    const context = { definitions: [], used: new Map() };
    rustType(entry.schema, rootName, context);
    lines.push(`pub mod ${moduleName} {`, '    use super::*;', '');
    for (const line of context.definitions) lines.push(line ? `    ${line}` : '');
    lines.push('}', '');
  }
  return `${lines.join('\n')}\n`;
}

function rustType(schema, suggestedName, context) {
  if (schema.$ref === 'T0' || schema.$id === 'T0') return 'JsonValue';

  if (Array.isArray(schema.anyOf)) {
    const literals = schema.anyOf.filter(
      (item) => Object.hasOwn(item, 'const') && typeof item.const === 'string',
    );
    if (literals.length === schema.anyOf.length) {
      const enumName = uniqueName(suggestedName, context.used);
      const variants = literals.map((item) => ({
        value: item.const,
        name: rustVariant(item.const),
      }));
      context.definitions.push(
        '#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]',
        `pub enum ${enumName} {`,
        ...variants.flatMap(({ value, name }) => [
          `    #[serde(rename = ${JSON.stringify(value)})]`,
          `    ${name},`,
        ]),
        '}',
        '',
      );
      return enumName;
    }
    const nonNull = schema.anyOf.filter((item) => item.type !== 'null');
    const hasNull = nonNull.length !== schema.anyOf.length;
    if (hasNull && nonNull.length === 1) {
      return `Option<${rustType(nonNull[0], suggestedName, context)}>`;
    }
    const enumName = uniqueName(suggestedName, context.used);
    const variants = unique(
      schema.anyOf.map((item, index) => rustType(item, `${enumName}Variant${index + 1}`, context)),
    );
    context.definitions.push(
      '#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]',
      '#[serde(untagged)]',
      `pub enum ${enumName} {`,
      ...variants.map((type, index) => `    Variant${index + 1}(${type}),`),
      '}',
      '',
    );
    return enumName;
  }

  if (Object.hasOwn(schema, 'const')) {
    if (schema.const === 1) return 'ContractVersion1';
    if (typeof schema.const === 'string') {
      const enumName = uniqueName(suggestedName, context.used);
      context.definitions.push(
        '#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]',
        `pub enum ${enumName} {`,
        `    #[serde(rename = ${JSON.stringify(schema.const)})]`,
        `    ${rustVariant(schema.const)},`,
        '}',
        '',
      );
      return enumName;
    }
  }

  if (schema.type === 'object') {
    if (schema.patternProperties || schema.additionalProperties === true) {
      const valueSchema = schema.patternProperties
        ? Object.values(schema.patternProperties)[0]
        : undefined;
      return `std::collections::BTreeMap<String, ${valueSchema ? rustType(valueSchema, `${suggestedName}Value`, context) : 'JsonValue'}>`;
    }
    const structName = uniqueName(suggestedName, context.used);
    const required = new Set(schema.required ?? []);
    const fields = [];
    for (const [property, propertySchema] of Object.entries(schema.properties ?? {})) {
      const fieldName = rustFieldName(property);
      let type = rustType(propertySchema, `${structName}${pascal(property)}`, context);
      if (!required.has(property) && !type.startsWith('Option<')) type = `Option<${type}>`;
      const attributes = [];
      if (fieldName !== property)
        attributes.push(`    #[serde(rename = ${JSON.stringify(property)})]`);
      if (!required.has(property))
        attributes.push('    #[serde(default, skip_serializing_if = "Option::is_none")]');
      fields.push(...attributes, `    pub ${fieldName}: ${type},`);
    }
    context.definitions.push(
      '#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]',
      '#[serde(deny_unknown_fields)]',
      `pub struct ${structName} {`,
      ...(fields.length > 0 ? fields : ['    // The schema defines an empty closed object.']),
      '}',
      '',
    );
    return structName;
  }

  if (schema.type === 'array') {
    return `Vec<${rustType(schema.items ?? {}, `${suggestedName}Item`, context)}>`;
  }
  if (schema.type === 'string') return 'String';
  if (schema.type === 'integer') return schema.minimum >= 0 ? 'u64' : 'i64';
  if (schema.type === 'number') return 'f64';
  if (schema.type === 'boolean') return 'bool';
  if (schema.type === 'null') return '()';
  return 'JsonValue';
}

function rootTypeName(schema, fallback) {
  const match = /\/([^/]+)\.schema\.json$/.exec(schema.$id ?? '');
  return pascal(match?.[1] ?? fallback);
}

function pascal(value) {
  const result = String(value)
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
  return /^\d/.test(result) ? `V${result}` : result || 'Anonymous';
}

const pythonReserved = new Set([
  'class',
  'def',
  'from',
  'global',
  'import',
  'in',
  'is',
  'lambda',
  'not',
  'or',
  'pass',
  'raise',
  'return',
  'try',
  'while',
  'with',
  'yield',
  'type',
]);
function pythonFieldName(value) {
  const snake = String(value)
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^A-Za-z0-9_]/g, '_')
    .toLowerCase();
  return pythonReserved.has(snake) || /^\d/.test(snake) ? `${snake}_` : snake;
}

const rustReserved = new Set([
  'as',
  'break',
  'const',
  'continue',
  'crate',
  'else',
  'enum',
  'extern',
  'false',
  'fn',
  'for',
  'if',
  'impl',
  'in',
  'let',
  'loop',
  'match',
  'mod',
  'move',
  'mut',
  'pub',
  'ref',
  'return',
  'self',
  'Self',
  'static',
  'struct',
  'super',
  'trait',
  'true',
  'type',
  'unsafe',
  'use',
  'where',
  'while',
  'async',
  'await',
  'dyn',
]);
function rustFieldName(value) {
  const snake = String(value)
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^A-Za-z0-9_]/g, '_')
    .toLowerCase();
  return rustReserved.has(snake) || /^\d/.test(snake) ? `${snake}_` : snake;
}

function rustVariant(value) {
  const variant = pascal(value);
  return rustReserved.has(variant) ? `${variant}Value` : variant;
}

function uniqueName(suggested, used) {
  const count = used.get(suggested) ?? 0;
  used.set(suggested, count + 1);
  return count === 0 ? suggested : `${suggested}${count + 1}`;
}

function unique(values) {
  return [...new Set(values)];
}

function pyLiteral(value) {
  if (value === true) return 'True';
  if (value === false) return 'False';
  if (value === null) return 'None';
  if (typeof value === 'string') return JSON.stringify(value);
  return String(value);
}

await main();
